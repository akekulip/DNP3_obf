#!/usr/bin/env python3
"""Numbers-only evaluation report generated from the pipeline outputs; every value is read, none is typed.

Reads OUT/rows/rows_manifest.json, OUT/figures/{sufficiency,verdicts}.json and the T2-T4 CSV tables written by
run_evaluation.sh, and writes OUT/REPORT_NUMBERS.md: dataset completeness, the pre-registered verdicts, classifier
headline cells, overhead and delivery. Interpretation is written separately by a person after reading the figures.

  python3 scripts/analysis/eval_report.py OUT_DIR
"""
import argparse
import csv
import json
from pathlib import Path

DS = (5, 10, 15, 20)
ARMS = ('off', 'timing_only', 'size_only', 'combined')
LABEL = {'off': 'No obfuscation', 'timing_only': 'Timing', 'size_only': 'Size', 'combined': 'Timing+Size'}


def read_csv(path):
    with Path(path).open() as stream:
        return list(csv.DictReader(stream))


def num(value, digits=3):
    try:
        return ('%.' + str(digits) + 'f') % float(value)
    except (TypeError, ValueError):
        return 'n/a'


def table(header, rows):
    lines = ['| ' + ' | '.join(header) + ' |', '|' + '---|' * len(header)]
    return lines + ['| ' + ' | '.join(str(c) for c in row) + ' |' for row in rows]


def build(out):
    out = Path(out)
    manifest = json.loads((out / 'rows/rows_manifest.json').read_text())
    gate = json.loads((out / 'figures/sufficiency.json').read_text())
    verdicts = json.loads((out / 'figures/verdicts.json').read_text())
    t2 = read_csv(out / 'figures/T2_classifier_metrics.csv')
    t3 = read_csv(out / 'figures/T3_delivery.csv')
    t4 = read_csv(out / 'figures/T4_overhead.csv')
    blocks = manifest['blocks']
    lines = ['# Evaluation numbers (generated by scripts/analysis/eval_report.py; do not edit by hand)', '',
             'Campaign: `%s`. Rows: %d (rows.csv SHA-256 `%s`). Extractor problems: %d.' % (
                 manifest['campaign'], manifest['rows'], manifest['rows_sha256'], len(manifest['problems'])), '',
             '## Completeness', '',
             'Blocks completed: %d of %d; unexecuted: %d; failed or excluded: %s.' % (
                 sum(b['status'] == 'completed' for b in blocks), len(blocks),
                 sum(b['status'] == 'unexecuted' for b in blocks),
                 ', '.join('%s (%s: %s)' % (b['id'], b['status'], b.get('reason')) for b in blocks
                           if b['status'] not in ('completed', 'unexecuted')) or 'none'),
             'Sufficiency gate: **%s** (%s). Captures clean: %s.' % (
                 'PASS' if gate['gate_passed'] else 'FAIL', gate['rule'], gate['capture_clean'])]
    short = [k for k, v in gate['cells'].items() if not (v['train_blocks'] >= 8 and v['test_blocks'] >= 8
                                                         and v['test_windows_K64'] >= 8 and v['test_windows_K8'] >= 64)]
    lines += ['Cells below the gate: %s.' % (', '.join(short) if short else 'none'), '',
              '## Pre-registered verdicts', '',
              'Size falsifier (%s): **%s**, %d violating responses.' % (
                  verdicts['size']['rule'], 'FALSIFIED' if verdicts['size']['falsified'] else 'not falsified',
                  verdicts['size']['violations']), '',
              'Timing falsifier: %s' % ' '.join(verdicts['timing']['rule'].split()), '']
    rows = []
    for key, cell in sorted(verdicts['timing']['cells'].items(),
                            key=lambda kv: (int(kv[0].split('/')[0][1:]), kv[0])):
        by_k = cell['classifier_by_k']
        rows.append([key, num(cell['median_spread_ms']), num(cell['off_median_spread_ms']),
                     'yes' if cell['spread_falsified'] else 'no'] +
                    ['%s [%s, %s] %s' % (num(c.get('off_minus_arm')), num(c.get('lower')), num(c.get('upper')),
                                         'FALSIFIED' if c.get('falsified') else 'ok') if 'unavailable' not in c
                     else 'n/a (%s)' % c['unavailable'] for c in (by_k.get(k) or by_k.get(str(k)) or {}
                                                                   for k in (8, 32, 64))])
    lines += table(['D/arm', 'class-median spread (ms)', 'off spread (ms)', 'spread falsified',
                    'off \u2212 arm NB BA, K=8 [95% CI]', 'K=32', 'K=64'], rows)
    lines += ['', '## Classifier headline (CLRT, joint and size; K = 64; naive Bayes and GMM block means with 95% CI; '
              'FF-ANN pooled on its random split)', '']
    rows = []
    for d in DS:
        for arm in ARMS:
            for feature in ('clrt', 'size', 'joint'):
                cells = {(r['classifier'], r['attacker']): r for r in t2 if r['d_ms'] == str(d) and r['arm'] == arm
                         and r['feature'] == feature and r['k'] == '64'}
                def show(key):
                    r = cells.get(key)
                    if not r or r['ba_pooled'] == '':
                        return 'n/a'
                    if r['ba_block_mean'] == '':
                        return num(r['ba_pooled'])
                    return '%s [%s, %s]' % (num(r['ba_block_mean']), num(r['ci_lower']), num(r['ci_upper']))
                rows.append([d, LABEL[arm], feature, show(('nb', 'retrained')), show(('nb', 'pre_deployment')),
                             show(('ff_ann', 'retrained')), show(('gmm', 'retrained'))])
    lines += table(['D (ms)', 'Arm', 'Feature', 'NB retrained', 'NB pre-deployment', 'FF-ANN', 'GMM'], rows)
    lines += ['', '## Overhead (relative to the same block\'s no-obfuscation arm)', '']
    rows = [[r['d_ms'], LABEL[r['arm']], num(r['pad_READ_B'], 1), num(r['pad_SELECT_B'], 1), num(r['pad_OPERATE_B'], 1),
             num(r['bytes_per_txn_pct'], 1), '%s %s' % (num(r['added_p50_ms']), r['added_p50_ci']),
             '%s %s' % (num(r['added_p95_ms']), r['added_p95_ci']), num(r['txn_per_s'], 1)] for r in t4]
    lines += table(['D (ms)', 'Arm', 'pad READ (B)', 'pad SELECT (B)', 'pad OPERATE (B)', 'bytes/txn (+%)',
                    'added p50 (ms) [95% CI]', 'added p95 (ms) [95% CI]', 'txn/s'], rows)
    lines += ['', '## Delivery', '']
    rows = [[r['d_ms'], LABEL[r['arm']], r['blocks'], r['exchanges'], r['outcome_ok'], r['application_ok'],
             '%s/%s' % (r['crob_success'], r['sbo']), r['retransmitted_segments'], r['kernel_drops'], r['piggyback']]
            for r in t3]
    lines += table(['D (ms)', 'Arm', 'blocks', 'exchanges', 'outcome OK', 'application OK', 'CROB SUCCESS',
                    'retransmitted segments', 'capture drops', 'piggyback'], rows)
    (out / 'REPORT_NUMBERS.md').write_text('\n'.join(lines) + '\n')
    return out / 'REPORT_NUMBERS.md'


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('out', type=Path)
    args = parser.parse_args(argv)
    print(build(args.out))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
