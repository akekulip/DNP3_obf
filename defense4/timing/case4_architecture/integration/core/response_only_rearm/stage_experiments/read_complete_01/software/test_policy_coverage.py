"""Coverage of the declared READ profile for the SELECTED policy (policy/policy.json), real encoder.

Every structure class x length case generated by policy/select_policy.py (multi-type mixes, 8/16-bit range
qualifiers, natural and max-first framing, every first-frame cut, retained captured shapes) must reach a
selected target with original application header/object bytes and decoded points preserved, synthetic
padding confined to the reserved range with zero flags/value. Out-of-profile inputs must be explicit.
"""
import json, pathlib, sys
import pytest
HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / 'policy'))
import select_policy as sp  # noqa: E402
gp, s = sp.gp, sp.std
POLICY = json.loads((HERE.parent / 'policy/policy.json').read_text())
TARGETS = POLICY['selected']['targets']
RETAINED, _ = sp.load_retained()
CASES = sp.profile_cases(RETAINED)


def test_policy_is_frozen_selection():
    assert TARGETS == [141, 247, 401]
    assert POLICY['profile']['reserved_padding_range'] == [1024, 4095]


@pytest.mark.parametrize('chunk', range(0, len(CASES), 500))
def test_every_profile_case_reaches_a_target(chunk):
    for cid, req, raw in CASES[chunk:chunk + 500]:
        r = gp.pad_read(req, raw, TARGETS, pad_start=1024, pad_stop=4095, max_app_bytes=2048)
        assert r.status in ('padded', 'already_at_target'), (cid, len(raw), r.reason)
        assert len(r.output) == r.target and r.target in TARGETS and r.target >= len(raw)
        _, app = gp.one_fragment(raw)
        _, out = gp.one_fragment(r.output)
        assert out[:4] == app[:4] and out.endswith(app[4:]), cid
        orig = s.check_read_response(s.fragment_user(app))[1]
        pts = s.check_read_response(s.fragment_user(out))[1]
        assert pts[r.padding_points:] == orig, cid
        pad = pts[:r.padding_points]
        assert all(g == 1 and v == 2 and 1024 <= i <= 4095 for g, v, i, _ in pad), cid
        assert all(val == b'\x00' for *_, val in pad), cid
        assert POLICY['selected']['required_index_range'][1] >= 1024 + r.padding_points - 1


def test_workload_shapes_use_prefix_construction():
    for cid, req, raw in [c for c in CASES if c[0].startswith('F4_')]:
        r = gp.pad_read(req, raw, TARGETS, pad_start=1024, pad_stop=4095, max_app_bytes=2048)
        assert r.status == 'already_at_target' or r.construction == 'prefix', cid


def test_target_boundaries():
    # every native length that is exactly a target is left unchanged (explicit status), and target+1 moves up
    by_len = {}
    for cid, req, raw in CASES:
        by_len.setdefault(len(raw), (cid, req, raw))
    for t in TARGETS:
        if t in by_len:
            r = gp.pad_read(by_len[t][1], by_len[t][2], TARGETS, pad_start=1024, pad_stop=4095)
            assert r.status == 'already_at_target' and r.output == by_len[t][2]
        if t + 1 in by_len and t != TARGETS[-1]:
            r = gp.pad_read(by_len[t + 1][1], by_len[t + 1][2], TARGETS, pad_start=1024, pad_stop=4095)
            assert r.target > t


def test_out_of_profile_is_explicit():
    big = sp.encode(sp.mix_app(330, 'g30v1'), [249, 81])      # 330 app octets: encoded > 377
    assert len(big) > 377
    r = gp.pad_read(sp.REQ, big, TARGETS, pad_start=1024, pad_stop=4095)
    assert r.status in ('unreachable', 'padded')                 # never silent: padded only to a real target
    if r.status == 'unreachable':
        assert r.output == big and r.target is None
    huge = sp.encode(sp.mix_app(600, 'g30v1'), [249, 249, 102])
    r = gp.pad_read(sp.REQ, huge, TARGETS, pad_start=1024, pad_stop=4095)
    assert r.status == 'unreachable' and r.output == huge
    ctl = sp.encode(bytes.fromhex('c3810000') + bytes([12, 1, 0x28, 1, 0, 0, 0]) + bytes(11))
    with pytest.raises(Exception):
        gp.pad_read(sp.REQ, ctl, TARGETS, pad_start=1024, pad_stop=4095)
    overlap = sp.encode(bytes.fromhex('c3810000') + bytes([1, 2, 1]) + (1020).to_bytes(2, 'little') + (1030).to_bytes(2, 'little') + bytes(11))
    with pytest.raises(gp.UnsupportedRead):
        gp.pad_read(sp.REQ, overlap, TARGETS, pad_start=1024, pad_stop=4095)
