def _evaluate(tmp_path, monkeypatch, source, pad_expect, exp, reads=9):
    """evaluate() over a retained m1_two_read_01 master/outstation record (9 READs: 5 mixed, 4 integrity); the
    wire and capture analyzers are faked, clrt.analyze is a spy."""
    for name in ('master.json', 'outstation.json'):
        shutil.copy(str(M1 / source / name), str(tmp_path / name))
    policies = []
    monkeypatch.setattr(vc.wc, 'analyze', lambda *a: {'returned_integrity': {'dnp3_crc_bad': [], 'tcp_checksum_bad': []},
                                                      'unmatched_sent': [], 'unmatched_returned': [],
                                                      'duplicate_returned': []})
    monkeypatch.setattr(vc.clrt, 'analyze', lambda *a, **k: policies.append(k) or {'summary': {}})
    monkeypatch.setattr(vc, 'close_proof', lambda *a: True)
    controls = dict(read_pause_ms=25, run_sbo=True, close_grace_ms=0, read_schedule='mixed_full', db='base')
    if pad_expect:
        controls['pad_expect'] = pad_expect
    failures = vc.evaluate(tmp_path, PORT, 'graceful', 1, {'ok': True, 'master_rc': 0, 'endpoint_controls': controls},
                           reads=reads, image_len=61, read_schedule='mixed_full', db='base', pad_expect=pad_expect,
                           read_classes=exp)
    return failures, policies


def _per_class(failures):
    return [f for f in failures if f.startswith(('READ ', 'reads_per_class', 'master reads records', 'read_commands',
                                                 'master pad_expect', 'master read_schedule', 'master db'))]


def test_evaluate_checks_real_padded_records_per_class(tmp_path, monkeypatch):
    exp = expectation(9)
    failures, policies = _evaluate(tmp_path, monkeypatch, 'padded_v0', PAD, exp)
    assert policies == [{'read_policy': {'classes': exp['classes']}}]
    assert _per_class(failures) == [], failures
    assert 'connection result or effective controls failed' not in failures


def test_evaluate_fails_native_records_against_a_padded_declaration(tmp_path, monkeypatch):
    failures, _ = _evaluate(tmp_path, monkeypatch, 'native_v0', PAD, expectation(9))
    assert "master pad_expect='none', expected 'mixed=26,integrity=4'" in failures
    assert any('padding expected 0 received 0, declared 26' in f for f in failures)


def test_evaluate_fails_padding_seen_on_an_off_declaration(tmp_path, monkeypatch):
    failures, _ = _evaluate(tmp_path, monkeypatch, 'padded_v0', None, expectation(9))
    assert "master pad_expect='mixed=26,integrity=4', expected 'none'" in failures


def test_evaluate_fails_a_wrong_slot_order(tmp_path, monkeypatch):
    exp = expectation(9)
    exp['order'] = ['integrity', 'mixed']
    failures, _ = _evaluate(tmp_path, monkeypatch, 'padded_v0', PAD, exp)
    assert any(f.startswith('READ 0: class') for f in failures)


