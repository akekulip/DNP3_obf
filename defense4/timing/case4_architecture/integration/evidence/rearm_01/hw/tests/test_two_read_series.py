def _argv(command):
    argv = shlex.split(command)
    return argv[argv.index('-c') + 3:]                                # after: python3 -c CODE script


def _flag(argv, name):
    return argv[argv.index(name) + 1] if name in argv else None


def test_series_command_carries_the_exact_padded_declaration(monkeypatch):
    module, cfg = two_read_config()
    campaign = campaign_of(module, cfg, 'series_cmd_two_read')
    calls = []

    def fake_run_unit(self, unit, port):
        calls.append(module.base.runner.vision_cmd(self.label(unit), port, unit['reads'], 8, 0, 0, 12345))

    monkeypatch.setattr(module.candidate_campaign.CandidateCampaign, 'run_unit', fake_run_unit)
    campaign.run_unit(campaign.units()[0], 59420)
    argv = _argv(calls[0])
    assert campaign._series_arm is None                               # reset after the unit
    assert _flag(argv, '--read-schedule') == 'mixed_full'
    assert _flag(argv, '--db') == 'base'
    assert _flag(argv, '--endpoint-binary') == 'case4_socket_gate_read_schedule'
    assert _flag(argv, '--pad-expect') == PAD
    exp = module.standards.read_class_expectations(cfg, campaign.arms[0], {'reads': 20})
    assert _flag(argv, '--read-classes') == json.dumps(exp, sort_keys=True, separators=(',', ':'))
    assert json.loads(_flag(argv, '--read-classes'))['classes'] == {
        'mixed': {'native': 91, 'image': 141, 'count': 10, 'native_segments': [91]},
        'integrity': {'native': 247, 'image': 271, 'count': 10, 'native_segments': [247]}}
    assert '--read-image-len' not in argv
    assert _flag(argv, '--image-len') == '61' and _flag(argv, '--padding') == '1'
    # the series command parses on vision_candidate's own CLI and passes its validation
    assert vc.main([a for a in argv if a != '--apply']) == 0           # offline plan, never --apply


