def config_pktgen(bi, tgts, a, out, chk, template=None):
    """Configure the generator: port, buffer template, one-shot timer app.

    Sequence and field names from the SDE's own example,
    pkgsrc/p4-examples/p4_16_programs/tna_pktgen/test.py (the timer_one_shot
    case), and the schema install/share/bf_rt_shared/bf_rt_pktgen_tf1.json.

    The app is left DISABLED. Enabling it starts the countdown and fires the
    batch, which is what fire_pktgen() does per trial.
    """
    import bfrt_grpc.client as gc
    if template is None:
        template = build_template(a.trial_id)

    # --- (1) port_cfg: run the generator on dp68 ---------------------------
    # A one-shot TIMER app needs only pktgen_enable. recirculation_enable and
    # pattern_matching_enable are for recirc-PATTERN triggers; they are read back
    # and reported but deliberately not written, so nothing else on dp68 is
    # disturbed.
    #
    # TODO(silicon): this is the SDE example's timer sequence
    # (pkgsrc/p4-examples/p4_16_programs/tna_pktgen/test.py, which sets ONLY
    # pktgen_enable for the timer app), but every previous pktgen run on THIS
    # switch used a recirc-PATTERN trigger, which additionally needs
    # recirculation_enable and pattern_matching_enable. Whether a timer app is
    # happy with pktgen_enable alone here is therefore not yet observed.
    # RESOLVING CHECK: the "pktgen pkt_counter" row after fire_pktgen(). It reads
    # 128 if the app fires. If it reads 0, add recirculation_enable=True (and
    # then pattern_matching_enable=True) to the write below and re-run.
    pcfg = get_table(bi, PKTGEN_PORT_CFG, chk)
    if pcfg is not None:
        okp = False
        for _tn, tgt in tgts:
            try:
                pcfg.entry_mod(tgt,
                               [pcfg.make_key([gc.KeyTuple("dev_port", a.port_pgen)])],
                               [pcfg.make_data([gc.DataTuple("pktgen_enable",
                                                             bool_val=True)])])
                okp = True
                break
            except Exception:
                continue
        got, err, _t = _port_entry(pcfg, tgts, a.port_pgen)
        out["pktgen_port_cfg"] = got if not err else {"err": err}
        if okp and not err and got.get("pktgen_enable"):
            chk.ok("pktgen enabled on dp%d" % a.port_pgen, str(got))
        else:
            chk.fail("pktgen enabled on dp%d" % a.port_pgen,
                     "write_ok=%s readback=%s" % (okp, got if not err else err))

    # --- (2) pkt_buffer: the 64-byte template ------------------------------
    # The buffer holds ONLY what follows the 6-byte generator header, which the
    # hardware prepends; the P4 extracts and never emits it, so what reaches the
    # queue is exactly these bytes. Offset must be 16-byte aligned.
    #
    # TODO(silicon): that pkt_len counts BUFFER bytes and excludes the 6-byte
    # generator header is read off the SDE example, where a 100-byte buffer is
    # written with pkt_len=100 and the P4 extracts a 6-byte pgen header before
    # Ethernet, and the test then verifies the received packet equals the
    # 100-byte buffer exactly. It has not been measured here.
    # RESOLVING CHECK: the P4 counters after a trial. If the offset assumption is
    # wrong the ethertype does not land at byte 12 of the post-header frame, the
    # parser's 0x88C3 test fails, and every packet lands on drop_non_oracle
    # instead of the enq_* slots. So: drop_non_oracle == 0 and
    # enq_ablock+enq_ack+enq_rblock+enq_resp == 128 confirms the layout.
    pbuf = get_table(bi, PKTGEN_PKT_BUFFER, chk)
    if pbuf is not None:
        wrote = False
        for _tn, tgt in tgts:
            try:
                pbuf.entry_mod(
                    tgt,
                    [pbuf.make_key([gc.KeyTuple("pkt_buffer_offset", a.buf_offset),
                                    gc.KeyTuple("pkt_buffer_size", len(template))])],
                    [pbuf.make_data([gc.DataTuple("buffer", bytearray(template))])])
                wrote = True
                break
            except Exception as e:
                out["pkt_buffer_err"] = str(e)[:90]
        out["pkt_buffer"] = {"offset": a.buf_offset, "size": len(template),
                             "trial_id": a.trial_id,
                             "hex": template.hex()}
        if wrote:
            chk.ok("pkt_buffer template written",
                   "%d B at offset %d, trial_id=%d" % (len(template), a.buf_offset,
                                                       a.trial_id))
        else:
            chk.fail("pkt_buffer template written", out.get("pkt_buffer_err", "unknown"))

    # --- (3) app_cfg: one-shot timer, ONE batch of N_PACKETS ---------------
    # Counts are ZERO-BASED: batch_count_cfg=0 is one batch and
    # packets_per_batch_cfg=127 is 128 packets.
    #
    # increment_source_port MUST be False. With it true the driver caps the batch
    # at 127-68=59 tokens and would silently reject 128.
    #
    # pipe_local_source_port is REQUIRED on this silicon despite the SDE's
    # "implicit on Tofino-1" note: it sets the ingress_port the generated packets
    # carry, and without it they arrive on the wrong port, miss the parser's
    # from_pgen path and are dropped (the localising symptom is pkt_counter=N
    # with the P4's traced counter at 0 and drop_bad_port at N).
    acfg = get_table(bi, PKTGEN_APP_CFG, chk)
    if acfg is not None:
        flds = [
            gc.DataTuple("timer_nanosec", int(a.timer_ns)),
            gc.DataTuple("pkt_len", len(template)),
            gc.DataTuple("pkt_buffer_offset", a.buf_offset),
            gc.DataTuple("pipe_local_source_port", a.port_pgen),
            gc.DataTuple("increment_source_port", bool_val=False),
            gc.DataTuple("batch_count_cfg", 0),
            gc.DataTuple("packets_per_batch_cfg", N_PACKETS - 1),
            gc.DataTuple("ipg", 0),
            gc.DataTuple("ibg", 0),
            gc.DataTuple("trigger_counter", 0),
            gc.DataTuple("batch_counter", 0),
            gc.DataTuple("pkt_counter", 0),
            gc.DataTuple("app_enable", bool_val=False),
        ]
        used_tgt = None
        for tn, tgt in tgts:
            try:
                acfg.entry_mod(tgt, [acfg.make_key([gc.KeyTuple("app_id", a.app_id)])],
                               [acfg.make_data(flds, "trigger_timer_one_shot")])
                used_tgt = tn
                break
            except Exception as e:
                out["app_cfg_err"] = str(e)[:90]
        out["app_cfg"] = {"app_id": a.app_id, "trigger": "trigger_timer_one_shot",
                          "timer_nanosec": a.timer_ns, "pkt_len": len(template),
                          "batch_count_cfg": 0,
                          "packets_per_batch_cfg": N_PACKETS - 1,
                          "increment_source_port": False,
                          "pipe_local_source_port": a.port_pgen,
                          "target": used_tgt}
        if used_tgt is None:
            chk.fail("pktgen app configured", out.get("app_cfg_err", "unknown"))
        else:
            chk.ok("pktgen app %d configured (one-shot timer)" % a.app_id,
                   "1 batch x %d pkts, target=%s" % (N_PACKETS, used_tgt))
            # The pipe-0 target is preferred so ONLY pipe 0's generator fires.
            # If the SDE only accepted the device-scope target, the pipe 1/2/3
            # generators fire too; their packets carry pipe-local port 68 in
            # their own pipe (dev_port 196/324/452), miss the parser's dp68 path
            # and land on the P4's drop_bad_port counter — harmless, but it must
            # be visible rather than assumed, so the counter is part of the gate.
            #
            # TODO(silicon): whether tf1.pktgen.app_cfg accepts a pipe-scoped
            # Target on this SDE is unverified; the SDE example uses device scope
            # ("Pipe All") and the Defense 2 setup used device scope too (safe
            # there because only pipe 0 could ever see its recirc trigger).
            # RESOLVING CHECK: out["app_cfg"]["target"] records which target was
            # accepted, and the P4 counter drop_bad_port distinguishes the two
            # cases unambiguously — 0 means pipe-0 scope held, 384 (3 x 128)
            # means all four generators fired and the other three pipes' packets
            # were correctly discarded. Either way traced == 128.
            if used_tgt != "pipe0":
                chk.warn("pktgen app scoped to pipe 0",
                         "the pipe-0 target was rejected; the app is device-scoped, so "
                         "all four pipe generators fire. Expect drop_bad_port = 3 x %d "
                         "and traced = %d." % (N_PACKETS, N_PACKETS))


def read_app_counters(bi, tgts, a):
    """(trigger_counter, batch_counter, pkt_counter) or Nones."""
    acfg = get_table(bi, PKTGEN_APP_CFG)
    if acfg is None:
        return None, None, None
    for _tn, tgt in tgts:
        got, err = get_entry(acfg, tgt, [("app_id", a.app_id)])
        if not err and got is not None:
            return (got.get("trigger_counter"), got.get("batch_counter"),
                    got.get("pkt_counter"))
    return None, None, None


def set_app_enable(bi, tgts, a, enable, chk):
    """Flip ONLY app_enable. The app does NOT auto-disable after a one-shot
    batch, so it must be driven False before it can be re-armed True."""
    import bfrt_grpc.client as gc
    acfg = get_table(bi, PKTGEN_APP_CFG, chk)
    if acfg is None:
        return False
    for _tn, tgt in tgts:
        try:
            acfg.entry_mod(tgt, [acfg.make_key([gc.KeyTuple("app_id", a.app_id)])],
                           [acfg.make_data([gc.DataTuple("app_enable",
                                                         bool_val=enable)])])
            return True
        except Exception:
            continue
    chk.fail("pktgen app_enable=%s" % enable, "no target accepted the write")
    return False


def fire_pktgen(bi, tgts, a, out, chk):
    """Fire exactly ONE batch: disable, then enable (which starts the countdown),
    wait for pkt_counter to reach N_PACKETS, then disable again so nothing can
    re-trigger."""
    set_app_enable(bi, tgts, a, False, chk)
    t0 = time.time()
    if not set_app_enable(bi, tgts, a, True, chk):
        return
    trig = batches = pkts = None
    deadline = time.time() + a.gen_timeout
    while time.time() < deadline:
        trig, batches, pkts = read_app_counters(bi, tgts, a)
        if pkts is not None and int(pkts) >= N_PACKETS:
            break
        time.sleep(0.05)
    dt = time.time() - t0
    set_app_enable(bi, tgts, a, False, chk)
    out["pktgen_fire"] = {"trigger_counter": trig, "batch_counter": batches,
                          "pkt_counter": pkts, "seconds": round(dt, 4)}
    if pkts is None:
        chk.fail("pktgen generated %d packets" % N_PACKETS, "pkt_counter unreadable")
    else:
        chk.expect("pktgen pkt_counter", int(pkts), N_PACKETS,
                   "(%.0f ms; app disabled again)" % (dt * 1e3))


