def read_occupancy(bi, tgt0, a, out, chk, require_nonempty=False):
    """Per-queue usage_cells / watermark_cells / drop_count_packets."""
    pg_id, pg_nr = resolve_pg(bi, tgt0, a.port_l, chk, out)
    if pg_id is None:
        chk.fail("occupancy", "could not resolve dp%d pg map" % a.port_l)
        return
    ctr = get_table(bi, TM_COUNTER_QUEUE, chk)
    if ctr is None:
        return
    print("dp8 queue occupancy [%s]" % TM_COUNTER_QUEUE)
    print("  %-8s %4s %9s %12s %18s" % ("role", "qid", "usage", "watermark",
                                        "drop_count_pkts"))
    occ = {}
    for role, qid, _act in ROLES:
        pgq = pg_queue_of(pg_nr, qid)
        got, err = get_entry(ctr, tgt0, [("pg_id", pg_id), ("pg_queue", pgq)])
        if err:
            chk.fail("%s counter readback" % role, err)
            continue
        rec = {"qid": qid, "pg_queue": pgq,
               "usage_cells": got.get("usage_cells"),
               "watermark_cells": got.get("watermark_cells"),
               "drop_count_packets": got.get("drop_count_packets")}
        occ[role] = rec
        print("  %-8s %4d %9s %12s %18s" % (role, qid, rec["usage_cells"],
                                            rec["watermark_cells"],
                                            rec["drop_count_packets"]))
        drops = rec["drop_count_packets"]
        if drops is not None and int(drops) != 0:
            chk.fail("%s drop_count_packets == 0" % role,
                     "TM DROPPED %s packet(s) — the trial is VOID" % drops)
        if require_nonempty:
            use, wm = rec["usage_cells"], rec["watermark_cells"]
            if use is None or wm is None:
                chk.fail("%s demonstrably nonempty" % role, "counter readback None")
            elif int(use) > 0 and int(wm) > 0:
                chk.ok("%s demonstrably nonempty" % role,
                       "usage_cells=%s watermark_cells=%s" % (use, wm))
            else:
                # INVALID, not an ordering FAILURE. The runner records it apart.
                chk.fail("%s demonstrably nonempty" % role,
                         "usage_cells=%s watermark_cells=%s — nothing was parked on "
                         "this queue, so the trial is INVALID (not an ordering "
                         "failure)" % (use, wm))
    print("")
    out["occupancy"] = occ
    out["all_queues_nonempty"] = (
        len(occ) == 4 and all((r.get("usage_cells") or 0) > 0
                              and (r.get("watermark_cells") or 0) > 0
                              for r in occ.values()))
    out["zero_queue_drops"] = all(
        int((r or {}).get("drop_count_packets") or 0) == 0 for r in occ.values())


def queue_counters(bi, tgt0, a):
    """{role: {usage_cells, watermark_cells, drop_count_packets, ...}}, QUIET.

    No printing, no PASS/FAIL rows, no `out` mutation. read_occupancy() above is
    the loud version used at the phase boundaries; this one is called in the
    drain-poll loop and by the clean-state assertion, where a row per read would
    be noise. Returns {} if the port-group map cannot be resolved.
    """
    pg_id, pg_nr = resolve_pg_quiet(bi, tgt0, a.port_l)
    if pg_id is None:
        return {}
    ctr = get_table(bi, TM_COUNTER_QUEUE)
    if ctr is None:
        return {}
    occ = {}
    for role, qid, _act in ROLES:
        pgq = pg_queue_of(pg_nr, qid)
        got, err = get_entry(ctr, tgt0, [("pg_id", pg_id), ("pg_queue", pgq)])
        if err:
            continue
        occ[role] = {"qid": qid, "pg_queue": pgq,
                     "usage_cells": _i(got.get("usage_cells")),
                     "watermark_cells": _i(got.get("watermark_cells")),
                     "drop_count_packets": _i(got.get("drop_count_packets"))}
    return occ


def reset_queue_counters(bi, tgt0, a, out, chk):
    """Zero the three tf1.tm.counter.queue fields on the four dp8 queues.

    All three are read-write in the schema, so a write of 0 is the documented
    clear. Each field is written INDEPENDENTLY so that one rejected field cannot
    prevent the others from being cleared.

    TODO(silicon): whether this SDE accepts a write to usage_cells (a live
    occupancy gauge, unlike the latched watermark and drop counters) is
    unconfirmed off-switch. RESOLVING CHECK: any rejected field appears as a WARN
    row naming that field; if usage_cells cannot be cleared, the preload gate
    still works because it tests usage_cells > 0, not equality.
    """
    import bfrt_grpc.client as gc
    pg_id, pg_nr = resolve_pg(bi, tgt0, a.port_l, chk, out)
    if pg_id is None:
        return
    ctr = get_table(bi, TM_COUNTER_QUEUE, chk)
    if ctr is None:
        return
    for role, qid, _act in ROLES:
        pgq = pg_queue_of(pg_nr, qid)
        key = ctr.make_key([gc.KeyTuple("pg_id", pg_id), gc.KeyTuple("pg_queue", pgq)])
        for fld in CTR_FIELDS:
            try:
                ctr.entry_mod(tgt0, [key], [ctr.make_data([gc.DataTuple(fld, 0)])])
            except Exception as e:
                chk.warn("reset %s %s" % (role, fld), "TODO(silicon): %s" % str(e)[:70])
    out["queue_counters_reset"] = True


def read_p4_counters(bi, tgt, out, chk):
    """Read the P4 ctr_oracle slots."""
    vals = {}
    for idx, name in CTR_SLOTS:
        vals[name] = ctr_read(bi, tgt, "ctr_oracle", idx, chk)
    out["p4_counters"] = vals
    print("P4 ctr_oracle: " + "  ".join("%s=%s" % (k, vals[k]) for _i, k in CTR_SLOTS))
