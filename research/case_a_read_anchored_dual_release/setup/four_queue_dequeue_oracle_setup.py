# 2. THE ROLE MAP — where the per-trial randomization lives
# ===========================================================================
def build_role_map(seed):
    """packet_id -> role name, exactly N_PER_ROLE of each, shuffled by `seed`.

    The multiset is FIXED (32 of each) and only the assignment is permuted, so
    every trial has identical queue backlogs and differs only in which generated
    packet goes where. Emission order is hardware-fixed at 0,1,...,127, so a
    dequeue order that tracks ROLE rather than packet_id cannot be an artifact of
    emission order.
    """
    pool = []
    for role, _qid, _act in ROLES:
        pool.extend([role] * N_PER_ROLE)
    random.Random(seed).shuffle(pool)
    return pool


def write_role_map(bi, tgt, a, out, chk, mapping):
    """Write all 128 tbl_role entries.

    Batched: one entry_add for all 128 keys, falling back to entry_mod when the
    entries already exist from a previous trial. Two RPCs at worst.

    TODO(silicon): whether this SDE accepts 128 keys in a single entry_add /
    entry_mod is unverified off-switch (the proven batched writes in this project
    are 4-entry TM writes). RESOLVING CHECK: the "tbl_role: 128 entries" row. If
    the batch is rejected, the failure detail carries the gRPC error and the loop
    can be changed to one RPC per entry — 128 RPCs is slow but has no effect on
    the measurement, because the map is fully written BEFORE the gate is closed
    and before any packet is generated.
    """
    import bfrt_grpc.client as gc
    t = get_table(bi, "tbl_role", chk)
    if t is None:
        return
    act_of = dict((role, act) for role, _q, act in ROLES)
    keys, datas = [], []
    for pid, role in enumerate(mapping):
        keys.append(t.make_key([gc.KeyTuple("hdr.pgen.packet_id", pid)]))
        datas.append(t.make_data([], act_of[role]))
    added = None
    try:
        t.entry_add(tgt, keys, datas)
        added = "entry_add"
    except Exception:
        try:
            t.entry_mod(tgt, keys, datas)
            added = "entry_mod"
        except Exception as e:
            chk.fail("tbl_role write (128 entries)", str(e)[:90])
            return
    counts = {}
    for r in mapping:
        counts[r] = counts.get(r, 0) + 1
    out["role_map"] = {"seed": a.seed, "path": added, "counts": counts,
                       "mapping": mapping}
    ok = all(counts.get(r) == N_PER_ROLE for r, _q, _a in ROLES)
    if ok:
        chk.ok("tbl_role: %d entries, %d per role" % (len(mapping), N_PER_ROLE),
               "%s, seed=%s" % (added, a.seed))
    else:
        chk.fail("tbl_role role balance", "counts=%s (want %d each)" % (counts, N_PER_ROLE))


