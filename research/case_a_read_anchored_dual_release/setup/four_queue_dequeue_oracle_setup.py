# 3. THE GLOBAL RELEASE GATE — a PORT-level max-rate shaper on dp8
# ===========================================================================
def _port_entry(tbl, tgts, dev_port):
    """entry_get for a dev_port-keyed table, trying each target in turn."""
    last = "no target tried"
    for tname, tgt in tgts:
        got, err = get_entry(tbl, tgt, [("dev_port", dev_port)])
        if not err:
            return got, None, tname
        last = err
    return None, last, None


def read_port_gate(bi, tgts, a, out, chk, label="gate"):
    """Read both gate tables for the gate port. Never writes."""
    shp = get_table(bi, TM_PORT_SHAPING, chk)
    cfg = get_table(bi, TM_PORT_SCHED_CFG, chk)
    rec = {"dev_port": a.gate_port}
    if shp is not None:
        got, err, tname = _port_entry(shp, tgts, a.gate_port)
        rec["sched_shaping"] = got if not err else {"err": err}
        rec["shaping_target"] = tname
    if cfg is not None:
        got, err, tname = _port_entry(cfg, tgts, a.gate_port)
        rec["sched_cfg"] = got if not err else {"err": err}
        rec["cfg_target"] = tname
    out.setdefault("port_gate", {})[label] = rec
    sh = rec.get("sched_shaping") or {}
    sc = rec.get("sched_cfg") or {}
    rec["armed"] = sc.get("max_rate_enable")
    print("port gate dp%d [%s]: max_rate_enable=%s unit=%s prov=%s max_rate=%s "
          "burst=%s speed=%s"
          % (a.gate_port, label, rec["armed"], sh.get("unit"), sh.get("provisioning"),
             sh.get("max_rate"), sh.get("max_burst_size"), sc.get("scheduling_speed")))
    return rec


def guard_gate_port(a, chk):
    """Refuse to gate a port that does not own the four queues.

    The queues under test live on dp8. A gate on any other port would hold
    traffic the dp8 scheduler had ALREADY ordered, and would pass meaninglessly.
    That is a silent-success failure mode, so it is refused, not warned about.
    """
    if a.gate_port == a.port_l:
        return True
    if a.i_know_the_gate_port_is_wrong:
        chk.warn("gate port override",
                 "gating dp%d, which does NOT own the four queues (dp%d). "
                 "Results are NOT a strict-priority verdict." % (a.gate_port, a.port_l))
        return True
    chk.fail("gate port owns the four queues",
             "--gate-port dp%d does not own the four queues (dp%d = PORT_L). "
             "Pass --i-know-the-gate-port-is-wrong to override."
             % (a.gate_port, a.port_l))
    return False


def set_port_gate(bi, tgts, a, closed, out, chk):
    """CLOSE (2 writes: shape, then arm) or OPEN (exactly ONE write).

    OPEN prefers max_rate_enable=False (disarm) over raising max_rate: disarming
    takes the token bucket OUT of the path, so the release boundary cannot depend
    on the bucket's banked credit or deficit state.
    """
    import bfrt_grpc.client as gc
    if not guard_gate_port(a, chk):
        return
    shp = get_table(bi, TM_PORT_SHAPING, chk)
    cfg = get_table(bi, TM_PORT_SCHED_CFG, chk)
    if shp is None or cfg is None:
        return

    def _mod(tbl, tuples, what):
        last = "no target tried"
        for tname, tgt in tgts:
            try:
                key = tbl.make_key([gc.KeyTuple("dev_port", a.gate_port)])
                tbl.entry_mod(tgt, [key], [tbl.make_data(tuples)])
                return tname, None
            except Exception as e:
                last = str(e)[:90]
        chk.fail(what, last)
        return None, last

    if closed:
        t0 = time.time()
        _tn1, e1 = _mod(shp, [
            gc.DataTuple("unit", str_val=a.gate_unit),
            gc.DataTuple("provisioning", str_val=a.gate_provisioning),
            gc.DataTuple("max_rate", int(a.gate_rate)),
            gc.DataTuple("max_burst_size", int(a.gate_burst))],
            "gate close: shaping params")
        _tn2, e2 = _mod(cfg, [gc.DataTuple("max_rate_enable", bool_val=True)],
                        "gate close: arm max_rate_enable")
        dt = time.time() - t0
        out["gate_close"] = {"dev_port": a.gate_port, "unit": a.gate_unit,
                             "max_rate": a.gate_rate, "max_burst_size": a.gate_burst,
                             "seconds": round(dt, 6), "n_writes": 2}
        if not e1 and not e2:
            chk.ok("gate CLOSED on dp%d" % a.gate_port,
                   "%s max_rate=%d burst=%d armed (%.2f ms, 2 writes)"
                   % (a.gate_unit, a.gate_rate, a.gate_burst, dt * 1e3))
    else:
        t0 = time.time()
        tn, err = _mod(cfg, [gc.DataTuple("max_rate_enable", bool_val=False)],
                       "gate open: disarm max_rate_enable")
        dt = time.time() - t0
        out["gate_open"] = {"dev_port": a.gate_port, "n_writes": 1,
                            "detail": "%s max_rate_enable=False" % TM_PORT_SCHED_CFG,
                            "seconds": round(dt, 6), "target": tn,
                            "release_write_unix": time.time()}
        if not err:
            chk.ok("gate OPENED on dp%d — ONE write" % a.gate_port,
                   "%s max_rate_enable=False (%.2f ms)" % (TM_PORT_SCHED_CFG, dt * 1e3))

    rb = read_port_gate(bi, tgts, a, out, chk,
                        label="after_close" if closed else "after_open")
    if closed:
        chk.expect("gate armed after close", rb.get("armed"), True)
        sh = rb.get("sched_shaping") or {}
        # A silently clamped burst is a STOP: banked burst credit is the main
        # threat to a clean release boundary.
        if sh.get("max_rate") is not None and int(sh["max_rate"]) != int(a.gate_rate):
            chk.fail("gate max_rate readback",
                     "wrote %d, read %s — the SDE quantized or rejected the rate"
                     % (a.gate_rate, sh.get("max_rate")))
        if (sh.get("max_burst_size") is not None
                and int(sh["max_burst_size"]) != int(a.gate_burst)):
            chk.fail("gate max_burst_size readback",
                     "wrote %d, read %s — a clamped burst banks credit that escapes "
                     "before the release" % (a.gate_burst, sh.get("max_burst_size")))
    else:
        chk.expect("gate disarmed after open", rb.get("armed"), False)


def restore_dp8(bi, tgts, a, out, chk):
    """Put dp8's scheduling configuration back to its ORIGINAL state."""
    import bfrt_grpc.client as gc
    shp = get_table(bi, TM_PORT_SHAPING, chk)
    cfg = get_table(bi, TM_PORT_SCHED_CFG, chk)
    if shp is None or cfg is None:
        return
    o = DP8_ORIGINAL

    def _mod(tbl, tuples, what):
        last = "no target tried"
        for tname, tgt in tgts:
            try:
                key = tbl.make_key([gc.KeyTuple("dev_port", a.port_l)])
                tbl.entry_mod(tgt, [key], [tbl.make_data(tuples)])
                return True
            except Exception as e:
                last = str(e)[:90]
        chk.fail(what, last)
        return False

    _mod(shp, [gc.DataTuple("unit", str_val=o["unit"]),
               gc.DataTuple("provisioning", str_val="UPPER"),
               gc.DataTuple("max_rate", int(o["max_rate"])),
               gc.DataTuple("max_burst_size", int(o["max_burst_size"]))],
         "restore dp8 shaping")
    _mod(cfg, [gc.DataTuple("max_rate_enable", bool_val=o["max_rate_enable"]),
               gc.DataTuple("scheduling_speed", str_val=o["scheduling_speed"])],
         "restore dp8 sched_cfg")

    rb = read_port_gate(bi, tgts, a, out, chk, label="after_restore")
    sh = rb.get("sched_shaping") or {}
    sc = rb.get("sched_cfg") or {}
    chk.expect("dp8 max_rate_enable restored", sc.get("max_rate_enable"),
               o["max_rate_enable"])
    chk.expect("dp8 max_rate restored",
               None if sh.get("max_rate") is None else int(sh["max_rate"]),
               o["max_rate"])
    chk.expect("dp8 unit restored", sh.get("unit"), o["unit"])
    chk.expect("dp8 max_burst_size restored",
               None if sh.get("max_burst_size") is None else int(sh["max_burst_size"]),
               o["max_burst_size"])
    chk.expect("dp8 scheduling_speed restored", sc.get("scheduling_speed"),
               o["scheduling_speed"])
    out["dp8_restored"] = True


