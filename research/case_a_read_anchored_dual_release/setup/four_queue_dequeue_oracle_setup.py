# ---- the generated frame template ------------------------------------------
# 64 bytes. The hardware PREPENDS its own 6-byte generator header, which the P4
# extracts and never emits, so what reaches the queue is exactly these 64 bytes
# with oracle.role and oracle.pkt_id stamped in. Locally-administered MACs; this
# frame never leaves the chip.
TPL_DST = bytes([0x02, 0x00, 0x00, 0x00, 0x88, 0xC3])
TPL_SRC = bytes([0x02, 0x00, 0x00, 0x00, 0x88, 0xC4])
TPL_ETYPE = 0x88C3        # .p4  const bit<16> ETHERTYPE_ORACLE4 = 0x88C3
TPL_LEN = 64


def build_template(trial_id):
    """The 64-byte packet-buffer template for one trial.

    Layout mirrors headers_t in the .p4 exactly:
        [0:6]   eth.dst
        [6:12]  eth.src
        [12:14] eth.etype   = 0x88C3
        [14:16] oracle.trial_id   <- the only per-trial field
        [16]    oracle.role       = 0, stamped by the enqueue action
        [17:19] oracle.pkt_id     = 0, stamped by the enqueue action
        [19:64] pad, never extracted, re-emitted verbatim by the deparser
    """
    b = bytearray(TPL_LEN)
    b[0:6] = TPL_DST
    b[6:12] = TPL_SRC
    b[12] = (TPL_ETYPE >> 8) & 0xFF
    b[13] = TPL_ETYPE & 0xFF
    b[14] = (trial_id >> 8) & 0xFF
    b[15] = trial_id & 0xFF
    # role and pkt_id stay zero; ingress stamps them.
    return bytes(b)


