def print_plan(a):
    print("")
    print("four-queue on-chip dequeue oracle — control plane")
    print("  program         : %s" % a.prog)
    print("  queues (dp%d)    : %s" % (a.port_l,
          ", ".join("%s=qid%d" % (r, q) for r, q, _x in ROLES)))
    print("  priority mode   : %s -> %s" % (a.priority_mode, priority_map(a)))
    print("  generator       : dp%d, app %d, one-shot timer %d ns, 1 batch x %d pkts"
          % (a.port_pgen, a.app_id, a.timer_ns, N_PACKETS))
    print("  role map        : %d per role, seed=%s" % (N_PER_ROLE, a.seed))
    print("  release gate    : PORT-level shaper on dp%d (%s rate=%d burst=%d);"
          % (a.gate_port, a.gate_unit, a.gate_rate, a.gate_burst))
    print("                    open = ONE write, %s max_rate_enable=False"
          % TM_PORT_SCHED_CFG)
    print("  NOT touched     : dp11, Hulk, sudo, any capture")
    print("")


def main(argv=None):
    a = parse_args(argv)
    chk = Checks()
    out = {"prog": a.prog, "authored_off_switch": True, "silicon_validated": False,
           "priority_mode": a.priority_mode, "seed": a.seed, "trial_id": a.trial_id}

    print_plan(a)
    if a.dry_run:
        out["role_map_preview"] = build_role_map(a.seed)[:16]
        print(chk.render())
        print("FQDQ " + json.dumps(out, default=str))
        if a.out:
            with open(a.out, "w") as fh:
                json.dump(out, fh, indent=2, default=str)
        return 0

    modes = [a.config, a.verify_only, a.priorities, a.role_map, a.gate_close,
             a.gate_open, a.gate_status, a.occupancy, a.reset_trace, a.trace_dump,
             a.trial, a.restore_dp8]
    if not any(modes):
        print("nothing to do: pass --trial, --config, --verify-only, --priorities, "
              "--role-map, --gate-close, --gate-open, --gate-status, --occupancy, "
              "--reset-trace, --trace-dump, --restore-dp8 or --dry-run",
              file=sys.stderr)
        return 2

    import bfrt_grpc.client as gc
    iface = gc.ClientInterface(a.grpc, client_id=a.client_id, device_id=0,
                               notifications=None)
    iface.bind_pipeline_config(a.prog)
    bi = iface.bfrt_info_get(a.prog)
    tgt = gc.Target(device_id=0, pipe_id=0xffff)
    tgt0 = gc.Target(device_id=0, pipe_id=0)
    # dev_port-keyed fixed-function tables: pipe-0 first (so only pipe 0's
    # generator is armed), device scope as fallback. Which one this SDE accepts
    # is not decidable off-switch, so both are tried and the winner is recorded.
    tgts = [("pipe0", tgt0), ("device", tgt)]

    if a.config:
        config_ports(bi, tgt, a, out, chk)
        write_priorities(bi, tgt0, a, out, chk, write=True)
        config_pktgen(bi, tgts, a, out, chk)
        read_port_gate(bi, tgts, a, out, chk, label="at_config")
    if a.verify_only:
        write_priorities(bi, tgt0, a, out, chk, write=False)
        read_port_gate(bi, tgts, a, out, chk, label="verify")
        read_occupancy(bi, tgt0, a, out, chk)
        read_p4_counters(bi, tgt, out, chk)
    if a.priorities:
        write_priorities(bi, tgt0, a, out, chk, write=True)
    if a.role_map:
        write_role_map(bi, tgt, a, out, chk, build_role_map(a.seed))
    if a.reset_trace:
        reset_trace(bi, tgt, out, chk)
    if a.gate_close:
        set_port_gate(bi, tgts, a, True, out, chk)
    if a.occupancy:
        read_occupancy(bi, tgt0, a, out, chk)
    if a.gate_status:
        read_port_gate(bi, tgts, a, out, chk, label="status")
    if a.gate_open:
        set_port_gate(bi, tgts, a, False, out, chk)
    if a.trace_dump:
        read_trace(bi, tgt, a, out, chk)
        read_p4_counters(bi, tgt, out, chk)
    if a.trial:
        run_trial(bi, tgt, tgt0, tgts, a, out, chk)
    if a.restore_dp8:
        restore_dp8(bi, tgts, a, out, chk)

    print(chk.render())
    out["n_fail"] = chk.n_fail
    out["checks"] = [{"result": r, "check": n, "detail": d} for r, n, d in chk.rows]
    print("FQDQ " + json.dumps(out, default=str))
    if a.out:
        with open(a.out, "w") as fh:
            json.dump(out, fh, indent=2, default=str)
        print("wrote %s" % a.out)
    return 1 if chk.n_fail else 0


if __name__ == "__main__":
    sys.exit(main())
