def resolve_pg(bi, tgt0, dev_port, chk, out):
    """READ the (pg_id, pg_port_nr) of a dev_port instead of guessing it."""
    pcfg = get_table(bi, TM_PORT_CFG, chk)
    if pcfg is None:
        return None, None
    got, err = get_entry(pcfg, tgt0, [("dev_port", dev_port)])
    if err:
        chk.fail("%s dp%d" % (TM_PORT_CFG, dev_port), err)
        return None, None
    pg_id, pg_nr = got.get("pg_id"), got.get("pg_port_nr")
    out.setdefault("port_cfg", {})["dp%d" % dev_port] = {
        "pg_id": pg_id, "pg_port_nr": pg_nr,
        "port_queues_count": got.get("port_queues_count")}
    chk.ok("dp%d port-group map (read, not guessed)" % dev_port,
           "pg_id=%s pg_port_nr=%s" % (pg_id, pg_nr))
    return pg_id, pg_nr


def pg_queue_of(pg_nr, qid):
    """pg_queue = pg_port_nr * 8 + qid (TF1: 8 queues per port in a port group)."""
    return pg_nr * 8 + qid


def priority_map(a):
    """The wanted max_priority per role for the selected mode."""
    if a.priority_mode == "custom":
        m = {}
        for item in (a.priority or "").split(","):
            item = item.strip()
            if not item:
                continue
            k, _sep, v = item.partition("=")
            m[k.strip().upper()] = v.strip()
        return m
    return dict(PRIORITY_MODES[a.priority_mode])


def config_ports(bi, tgt, a, out, chk):
    """dp8 MAC-near loopback. dp11 is NOT configured and Hulk is NOT involved."""
    import bfrt_grpc.client as gc
    port_tbl = bi.table_get("$PORT")
    try:
        lk = [port_tbl.make_key([gc.KeyTuple("$DEV_PORT", a.port_l)])]
        try:
            port_tbl.entry_del(tgt, lk)   # a live entry rejects a mode change
        except Exception:
            pass
        port_tbl.entry_add(tgt, lk, [port_tbl.make_data([
            gc.DataTuple("$SPEED", str_val="BF_SPEED_25G"),
            gc.DataTuple("$FEC", str_val="BF_FEC_TYP_NONE"),
            gc.DataTuple("$AUTO_NEGOTIATION", str_val="PM_AN_FORCE_DISABLE"),
            gc.DataTuple("$LOOPBACK_MODE", str_val="BF_LPBK_MAC_NEAR"),
            gc.DataTuple("$PORT_ENABLE", bool_val=True)])])
        chk.ok("dp%d MAC-near loopback" % a.port_l, "BF_LPBK_MAC_NEAR 25G")
    except Exception as e:
        chk.fail("dp%d MAC-near loopback" % a.port_l, str(e)[:90])
    out["ports_configured"] = [a.port_l]
    chk.ok("dp11 NOT configured", "this oracle has no host port by construction")


def write_priorities(bi, tgt0, a, out, chk, write=True):
    """Write and read back max_priority on the four dp8 queues.

    max_priority arbitrates among BACKLOGGED queues in the remaining-bandwidth
    pass. min_priority orders only the guaranteed pass and is INERT unless
    min_rate_enable is true — setting it instead of max_priority is precisely the
    silent configuration error the IBSPG root-cause repair found, so it is left
    alone here and max_rate/min_rate enables are forced off separately.
    """
    import bfrt_grpc.client as gc
    want = priority_map(a)
    out["priority_mode"] = a.priority_mode
    out["priority_want"] = want

    pg_id, pg_nr = resolve_pg(bi, tgt0, a.port_l, chk, out)
    if pg_id is None:
        chk.fail("priorities", "could not resolve dp%d pg map" % a.port_l)
        return
    q_cfg = get_table(bi, TM_SCHED_CFG, chk)
    if q_cfg is None:
        return
    q_map = get_table(bi, TM_QUEUE_MAP)

    got_map = {}
    for role, qid, _act in ROLES:
        pgq = pg_queue_of(pg_nr, qid)
        key = q_cfg.make_key([gc.KeyTuple("pg_id", pg_id), gc.KeyTuple("pg_queue", pgq)])
        if write:
            w = want.get(role)
            if w is None:
                chk.fail("%s priority" % role, "no value for this role in mode %s"
                         % a.priority_mode)
                continue
            try:
                q_cfg.entry_mod(tgt0, [key], [q_cfg.make_data([
                    gc.DataTuple("scheduling_enable", bool_val=True),
                    gc.DataTuple("max_rate_enable", bool_val=False),
                    gc.DataTuple("min_rate_enable", bool_val=False),
                    gc.DataTuple("max_priority", str_val=str(w))])])
            except Exception as e:
                chk.fail("%s max_priority write" % role, str(e)[:90])
                continue
        sc, err = get_entry(q_cfg, tgt0, [("pg_id", pg_id), ("pg_queue", pgq)])
        if err:
            chk.fail("%s sched_cfg readback" % role, err)
            continue
        dev_port = None
        if q_map is not None:
            qm, qerr = get_entry(q_map, tgt0, [("pg_id", pg_id), ("pg_queue", pgq)])
            if not qerr:
                dev_port = (qm or {}).get("dev_port")
        rec = {"qid": qid, "pg_queue": pgq,
               "max_priority": sc.get("max_priority"),
               "min_priority": sc.get("min_priority"),
               "scheduling_enable": sc.get("scheduling_enable"),
               "max_rate_enable": sc.get("max_rate_enable"),
               "min_rate_enable": sc.get("min_rate_enable"),
               "dwrr_weight": sc.get("dwrr_weight"),
               "dev_port": dev_port}
        out.setdefault("queues", {})[role] = rec
        got_map[role] = pnorm(rec["max_priority"])
        if write:
            chk.expect("%s max_priority" % role, pnorm(rec["max_priority"]),
                       pnorm(want.get(role)), "(qid %d, pg_queue %d)" % (qid, pgq))
        # A queue that is over its own max rate goes shaping-INELIGIBLE and the
        # TM serves a lower-priority eligible queue. That is not a priority
        # violation but it is indistinguishable from one, so it is asserted off.
        chk.expect("%s per-queue max_rate_enable is False" % role,
                   rec["max_rate_enable"], False)
        if dev_port is not None and int(dev_port) != a.port_l:
            chk.fail("%s maps to dp%d" % (role, a.port_l),
                     "queue.map reports dev_port=%s" % dev_port)

    out["priority_got"] = got_map
    print("")
    print("dp8 queue priorities (mode=%s)  [%s]" % (a.priority_mode, TM_SCHED_CFG))
    print("  %-8s %4s %10s %10s %10s %10s" % ("role", "qid", "want", "got",
                                              "sched_en", "max_rate_en"))
    for role, qid, _a in ROLES:
        r = out.get("queues", {}).get(role, {})
        print("  %-8s %4d %10s %10s %10s %10s"
              % (role, qid, want.get(role), r.get("max_priority"),
                 r.get("scheduling_enable"), r.get("max_rate_enable")))
    print("")
    # This readback is CONFIGURATION EVIDENCE ONLY. It says what was written.
    chk.warn("readback is not the proof",
             "max_priority readback shows what was WRITTEN. The behavioural "
             "verdict comes from the on-chip dequeue trace, via "
             "analysis/analyze_four_queue_dequeue.py")


