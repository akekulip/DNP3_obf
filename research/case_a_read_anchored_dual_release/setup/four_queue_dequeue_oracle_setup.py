def get_entry(tbl, tgt, keyfields, from_hw=True):
    """entry_get one key -> (data dict, None) or (None, error string)."""
    import bfrt_grpc.client as gc
    try:
        key = tbl.make_key([gc.KeyTuple(k, v) for k, v in keyfields])
    except Exception as e:
        return None, "make_key: %s" % str(e)[:90]
    try:
        got = None
        for d, _k in tbl.entry_get(tgt, [key], {"from_hw": from_hw}):
            got = d.to_dict()
        return (got, None) if got is not None else (None, "entry does not exist")
    except Exception as e:
        return None, "entry_get: %s" % str(e)[:90]


def get_table(bi, name, chk=None):
    """Resolve a bfrt table, tolerant of the pipeline prefix.

    P4 objects resolve as 'pipe.Ingress.<name>' on this SDE, but the prefix has
    differed between builds, so candidates are tried in order and a name scan is
    the last resort. Carried from ibspg_trace_read2.py:63, which is the reader
    that produced the two-queue result.
    """
    for cand in ("pipe.Ingress." + name, "Ingress." + name, name):
        try:
            return bi.table_get(cand)
        except Exception:
            continue
    try:
        for tn in bi.table_dict.keys():
            if tn.endswith("." + name) or tn.endswith("Ingress." + name):
                return bi.table_get(tn)
    except Exception:
        pass
    if chk is not None:
        chk.fail("table lookup '%s'" % name, "not found in bfrt info")
    return None


def _flatten_max(vals):
    """Collapse a register readback to one int.

    A Register read returns one value per pipe (and per SALU half), so the raw
    result is a list, sometimes nested. The oracle only ever writes from pipe 0,
    so every other element is the initial 0 and the maximum is the written value.
    Carried from ibspg_trace_read2.py:48.
    """
    ints = []
    stack = list(vals)
    while stack:
        v = stack.pop()
        if isinstance(v, (list, tuple)):
            stack.extend(v)
        elif isinstance(v, bool):
            ints.append(int(v))
        elif isinstance(v, int):
            ints.append(v)
    return max(ints) if ints else None


def _reg_value_from(dd):
    """Pull the single data value out of a register entry dict."""
    vals = []
    for kk, vv in dd.items():
        if kk == "$REGISTER_INDEX" or kk == "action_name" or kk.startswith("is_"):
            continue
        vals.append(vv)
    return _flatten_max(vals)


def reg_read(bi, tgt, name, idx, chk=None):
    """Read Register <name> at one index."""
    import bfrt_grpc.client as gc
    t = get_table(bi, name, chk)
    if t is None:
        return None
    k = t.make_key([gc.KeyTuple("$REGISTER_INDEX", idx)])
    try:
        for d, _ in t.entry_get(tgt, [k], {"from_hw": True}):
            return _reg_value_from(d.to_dict())
    except Exception as e:
        if chk is not None:
            chk.fail("reg_read %s[%d]" % (name, idx), str(e)[:90])
    return None


def reg_read_range(bi, tgt, name, n, chk=None):
    """Read Register <name> over indices 0..n-1, batched into ONE entry_get.

    The response is mapped back to an index using the $REGISTER_INDEX that the
    SDE echoes in the data dict, so response ORDER is never assumed. If the batch
    path fails for any reason the reader falls back to n single reads, which is
    slower but cannot be wrong.

    TODO(silicon): whether this SDE echoes $REGISTER_INDEX in the data dict is
    the one unverified assumption. RESOLVING CHECK: --trace-dump reports
    `index_source` as 'echoed' or 'fallback-perindex'; if it says 'fallback',
    the batch path was not usable and the per-index path produced the trace.
    """
    import bfrt_grpc.client as gc
    t = get_table(bi, name, chk)
    if t is None:
        return [None] * n, "table-missing"
    keys = [t.make_key([gc.KeyTuple("$REGISTER_INDEX", i)]) for i in range(n)]
    out = [None] * n
    try:
        seen = 0
        for d, k in t.entry_get(tgt, keys, {"from_hw": True}):
            dd = d.to_dict()
            idx = dd.get("$REGISTER_INDEX")
            if idx is None:
                try:
                    idx = k.to_dict()["$REGISTER_INDEX"]["value"]
                except Exception:
                    idx = None
            if idx is None:
                raise RuntimeError("no $REGISTER_INDEX echoed")
            idx = int(idx)
            if 0 <= idx < n:
                out[idx] = _reg_value_from(dd)
                seen += 1
        if seen == n:
            return out, "echoed"
    except Exception:
        pass
    # fallback: one read per index
    for i in range(n):
        out[i] = reg_read(bi, tgt, name, i, chk)
    return out, "fallback-perindex"


def ctr_read(bi, tgt, name, idx, chk=None):
    """Read PACKETS Counter <name> at <idx>.

    A Stats-ALU counter needs an explicit HW->SW sync before a control-plane
    read; from_hw alone returns a stale 0. Carried from ibspg_trace_read2.py:100.
    """
    import bfrt_grpc.client as gc
    t = get_table(bi, name, chk)
    if t is None:
        return None
    try:
        t.operations_execute(tgt, "SyncCounters")
    except Exception:
        pass
    k = t.make_key([gc.KeyTuple("$COUNTER_INDEX", idx)])
    vals = []
    try:
        for d, _ in t.entry_get(tgt, [k], {"from_hw": True}):
            dd = d.to_dict()
            if "$COUNTER_SPEC_PKTS" in dd:
                vals.append(dd["$COUNTER_SPEC_PKTS"])
    except Exception as e:
        if chk is not None:
            chk.warn("ctr_read %s[%d]" % (name, idx), str(e)[:80])
        return None
    return int(_flatten_max(vals) or 0)


def reg_zero(bi, tgt, name, idx, chk):
    """Write 0 into Register <name> at <idx>.

    The data field name is DISCOVERED from a read rather than guessed: it
    resolves as something like 'Ingress.<name>.f1' and the exact spelling has
    varied between builds.
    """
    import bfrt_grpc.client as gc
    t = get_table(bi, name, chk)
    if t is None:
        return False
    k = t.make_key([gc.KeyTuple("$REGISTER_INDEX", idx)])
    field = None
    try:
        for d, _ in t.entry_get(tgt, [k], {"from_hw": True}):
            for kk in d.to_dict():
                if kk == "$REGISTER_INDEX" or kk == "action_name" or kk.startswith("is_"):
                    continue
                field = kk
                break
    except Exception as e:
        chk.fail("reg_zero %s[%d] discover field" % (name, idx), str(e)[:80])
        return False
    if field is None:
        chk.fail("reg_zero %s[%d]" % (name, idx), "no data field found in readback")
        return False
    try:
        t.entry_mod(tgt, [k], [t.make_data([gc.DataTuple(field, 0)])])
        return True
    except Exception as e:
        chk.fail("reg_zero %s[%d] write" % (name, idx), str(e)[:80])
        return False


