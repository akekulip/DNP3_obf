#!/usr/bin/env python3.8
# =============================================================================
#  four_queue_dequeue_oracle_setup.py — control plane for the FOUR-QUEUE
#  on-chip TM dequeue-order oracle (p4/four_queue_dequeue_oracle.p4).
#
#  Runs ON THE SWITCH against the loaded program (bfruntime localhost:50052):
#
#    SDE=/home/decps/Downloads/bf-sde-9.13.2
#    SP=$SDE/install/lib/python3.8/site-packages
#    PYTHONPATH=$SP:$SP/tofino python3.8 four_queue_dequeue_oracle_setup.py --config
#
#  ---------------------------------------------------------------------------
#  THE MECHANISM, IN ONE PARAGRAPH
#
#  There is NO port-level scheduling enable on Tofino-1 (tf1.tm.port.sched_cfg
#  carries only max_rate_enable and scheduling_speed), so releasing N queues via
#  per-queue scheduling_enable is inescapably N separate writes — and draining
#  32 x 64-byte frames at 25G takes about 1.7 us, the SAME ORDER as the driver's
#  per-entry write latency. Enable ORDER could therefore decide drain order while
#  the experiment looked perfectly healthy. The fix is to leave every queue
#  scheduling-enabled and gate the PORT instead: a port-level max-rate shaper
#  sits ABOVE the queue scheduler, so ONE write holds all four queues and ONE
#  write makes them all servable at the same instant. The scheduler, not the
#  control plane's write order, then decides.
#
#  THE GATE MUST BE ON THE PORT THAT OWNS THE QUEUES (dp8). Gating any other
#  port would hold traffic the dp8 scheduler had ALREADY ordered, and would pass
#  meaninglessly. That is refused here, not warned about.
#
#  ---------------------------------------------------------------------------
#  WHY THE PACKETS COME FROM INSIDE THE CHIP
#
#  All traffic is generated by the Tofino packet generator on dp68 with a
#  one-shot TIMER trigger. No host is involved: dp11 is never configured, Hulk is
#  never contacted, no raw socket and no packet capture is required, and the
#  release-to-first-dequeue window is never gated by host scheduling. The 128
#  generated packets are byte-identical copies of ONE buffer template and differ
#  only in the hardware packet_id, so the ROLE assignment lives entirely in the
#  128-entry tbl_role map that this script rewrites, from a recorded seed, before
#  every trial. That is what makes the observed order provably not the emission
#  order: emission order is fixed by hardware at 0,1,2,...,127.
#
#  ---------------------------------------------------------------------------
#  SCOPE. This script configures and measures SCHEDULER PRIORITY only. It says
#  nothing about reservoir depth or about recirculation empty gaps; those remain
#  separate evidence. See reports/FOUR_QUEUE_DEQUEUE_ORACLE_REPORT.md.
#
#  Ports touched: dp8 (loopback, owns the queues) and dp68 (packet generator).
#  dp11 is NOT configured. Hulk is NOT contacted. sudo is NEVER invoked.
# =============================================================================
